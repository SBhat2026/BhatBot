// Writes phone-app/Sources/Secrets.swift (gitignored, mode 600) from the Mac's vault: the Mac's
// Funnel host + MCP token and the cloud host + cloud token. Prints which doors were filled, never
// the values. Run by phone-app/build-ipa.sh and build-sim.sh.
const { app } = require('electron');
app.setName('bhatbot');
app.whenReady().then(() => {
  const fs = require('fs'), os = require('os'), path = require('path');
  const out = path.join(__dirname, '../../../phone-app/Sources/Secrets.swift');
  let mac = { host: '', token: '' }, cloud = { host: '', token: '' };
  try {
    const credentials = require(path.join(__dirname, '../../../lib/credentials'));
    const c = credentials.resolveRefs(JSON.parse(fs.readFileSync(os.homedir() + '/.bhatbot/config.json', 'utf8')));
    const ok = (t) => typeof t === 'string' && t && !/^CRED_REF/.test(t);
    if (c.publicHost && ok(c.mcpToken)) mac = { host: 'https://' + String(c.publicHost).replace(/^https?:\/\//, '').replace(/\/+$/, ''), token: c.mcpToken };
    if (c.cloudUrl && ok(c.cloudToken)) cloud = { host: String(c.cloudUrl).replace(/\/+$/, ''), token: c.cloudToken };
  } catch (e) { console.log('SECRETS ERR', e.message); }
  const q = (s) => JSON.stringify(String(s));
  fs.writeFileSync(out, `// GENERATED by scripts/live/phone-secrets — do not commit (gitignored).\n`
    + `enum Secrets {\n  static let macHost = ${q(mac.host)}\n  static let macToken = ${q(mac.token)}\n`
    + `  static let cloudHost = ${q(cloud.host)}\n  static let cloudToken = ${q(cloud.token)}\n}\n`, { mode: 0o600 });
  console.log(`SECRETS mac:${mac.token ? 'yes' : 'no'} cloud:${cloud.token ? 'yes' : 'no'}`);
  app.exit(0);
});
